        private void btnGenerate_Click(object sender, EventArgs e)
        {
            try
            {
                int year = Convert.ToInt32(numYear.Value);
                int month = Convert.ToInt32(numMonth.Value);

                // Check if the monthly payment is already generated by iterating through lstYearMonth
                foreach (string ym in lstYearMonth.Items)
                {
                    string[] parts = ym.Split('-');
                    int existingYear = Convert.ToInt32(parts[0]);
                    int existingMonth = Convert.ToInt32(parts[1]);

                    if (existingYear == year && existingMonth == month)
                    {
                        MessageBox.Show("Monthly payments for this month have already been generated.", null, MessageBoxButtons.OK, MessageBoxIcon.Information);
                        return;
                    }
                }

                GeneratorMonthlyPayment generator = new GeneratorMonthlyPayment();
                int created = generator.GenerateMonthlyPayments(year, month);

                dataGridView.Rows.Clear();

                // Add each monthly payment in the Data View Grid
                foreach (MonthlyPayment p in generator.ListMonthlyPayments)
                {
                    string employeeText = p.payEmployee != null ? p.payEmployee.ToString() : string.Empty;
                    dataGridView.Rows.Add(p.idMonthlyPayment, employeeText, Math.Round(p.paySalaryGross, 2), Math.Round(p.paySalaryNet, 2), p.payBonusApplied);
                }

                if (created > 0)
                {
                    LoadYearMonthList();
                    LoadPaymentsForMonth(year, month);
                }
                else
                {
                    MessageBox.Show("No employees worked during this month. Thus, no monthly payments were generated.", "No Payments Generated", MessageBoxButtons.OK, MessageBoxIcon.Information);
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(ex.Message, ex.Source, MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void btnDelete_Click(object sender, EventArgs e)
        {
            int year = (int) numYear.Value;
            int month = (int) numMonth.Value;

            if (MessageBox.Show("Are you sure you want to delete all the monthly payments of " + year + "-" + month + "?", null,
                    MessageBoxButtons.YesNo, MessageBoxIcon.Question) != DialogResult.Yes)
            {
                return;
            }

            // User does not see the monthly payments, although they are not deleted yet
            dataGridView.Rows.Clear();

            string ymToRemove = year + "-" + month;
            bool found = false;

            // We search for the record with the month and year
            for (int i = 0; i < lstYearMonth.Items.Count && !found; i++)
            {
                string item = (string) lstYearMonth.Items[i];

                if (item.ToString() == ymToRemove)
                {
                    // And then remove it
                    lstYearMonth.Items.RemoveAt(i);
                    found = true;
                }
            }

            MonthlyPayment aux = new MonthlyPayment();
            List<MonthlyPayment> monthlyPayments = aux.ReadAllMonthlyPayments();

            // We delete each monthly payment which corresponds to month and year
            foreach (MonthlyPayment p in monthlyPayments)
            {
                if (p.payYear == year && p.payMonth == month)
                {
                    try
                    {
                        if (p.DeleteMonthlyPayment() != 1)
                        {
                            MessageBox.Show("An error occurred while deleting monthlyPayment " + p.idMonthlyPayment, null, MessageBoxButtons.OK);
                        }
                    }
                    catch (Exception ex)
                    {
                        MessageBox.Show(ex.Message, ex.Source, MessageBoxButtons.OK, MessageBoxIcon.Error);
                    }
                }
            }
        }

