        private void FormMonthlyPayments_Load(object sender, EventArgs e)
        {
            try
            {
                LoadYearMonthList();
            }
            catch (Exception ex)
            {
                MessageBox.Show(ex.Message, ex.Source, MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        // This method loads the list of all monthly payments and groups them by year and month
        private void LoadYearMonthList()
        {
            lstYearMonth.Items.Clear();

            MonthlyPayment aux = new MonthlyPayment();
            List<MonthlyPayment> payments = aux.ReadAllMonthlyPayments();

            List<string> yearMonths = new List<string>();

            foreach (MonthlyPayment p in payments)
            {
                string ym = p.payYear.ToString() + "-" + p.payMonth.ToString();
                if (!yearMonths.Contains(ym))
                {
                    yearMonths.Add(ym);
                }
            }

            yearMonths.Sort();
            yearMonths.Reverse();

            // We show the different groups in the list
            foreach (string ym in yearMonths)
            {
                lstYearMonth.Items.Add(ym);
            }
        }

        private void lstYearMonth_SelectedIndexChanged(object sender, EventArgs e)
        {
            if (lstYearMonth.SelectedItem != null)
            {
                string ym = lstYearMonth.SelectedItem.ToString();

                string[] parts = ym.Split('-');

                int year = Convert.ToInt32(parts[0]);
                int month = Convert.ToInt32(parts[1]);
                 
                numYear.Value = year;
                numMonth.Value = month;
                LoadPaymentsForMonth(year, month);
                
            }
        }

        // Shows in the Data View Grid the monthly payments which correspond to the year and month selected
        private void LoadPaymentsForMonth(int year, int month)
        {
            dataGridView.Rows.Clear();

            MonthlyPayment aux = new MonthlyPayment();
            List<MonthlyPayment> payments = aux.ReadAllMonthlyPayments();

            foreach (MonthlyPayment p in payments)
            {
                if (p.payYear == year && p.payMonth == month)
                {
                    string employeeText = p.payEmployee != null ? p.payEmployee.ToString() : string.Empty;
                    dataGridView.Rows.Add(p.idMonthlyPayment, employeeText, p.paySalaryGross, p.paySalaryNet, p.payBonusApplied);
                }
            }
        }

